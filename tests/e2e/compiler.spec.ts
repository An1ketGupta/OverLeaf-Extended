import { createHash, randomUUID } from "node:crypto";
import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { createDatabase } from "@overleaf-pro/db";
import { expect, test } from "@playwright/test";
import { requireTestDatabase } from "../../scripts/test-database.js";
import { verifyBrowserAccount } from "./account-helper.js";

const email = `compile-browser-${randomUUID()}@example.test`;
const origin = "http://127.0.0.1:5273";
test.afterAll(async () => {
  if (!process.env.TEST_DATABASE_URL) return;
  const db = createDatabase(requireTestDatabase());
  try {
    await db.pool.query('DELETE FROM "user" WHERE email=$1', [email]);
  } finally {
    await db.close();
  }
});
test("real browser compiler saves source, exports exact PDF, rejects stale/error output, cancels, recovers and analyzes generated bytes", async ({
  page,
  context,
}, testInfo) => {
  test.setTimeout(150_000);
  test.skip(
    !process.env.TEST_DATABASE_URL ||
      !existsSync("apps/web/public/compiler/manifest.json"),
    "Requires real PostgreSQL test database and compiler:prepare assets",
  );
  const signup = await context.request.post("/api/auth/sign-up/email", {
    headers: { origin },
    data: {
      name: "Compiler Browser",
      email,
      password: "synthetic-compiler-password-42",
    },
  });
  expect(signup.status()).toBe(200);
  await verifyBrowserAccount(
    context.request,
    email,
    "synthetic-compiler-password-42",
    origin,
  );
  const created = await context.request.post("/api/projects", {
    headers: { origin },
    data: { name: "Compiled resume", templateId: "resume-classic" },
  });
  expect(created.status()).toBe(201);
  const project = await created.json();
  await page.goto(`/projects/${project.id}`);
  const editor = page.getByRole("textbox", {
    name: "Source editor: main.tex",
    exact: true,
  });
  await expect(editor).toBeVisible();
  const status = page.getByRole("status", { name: "Compilation status" });
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compilation succeeded", { timeout: 60_000 });
  await expect(
    page.getByRole("img", { name: "PDF page 1 of 1" }),
  ).toBeVisible();
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  const download = await downloadEvent;
  const path = await download.path();
  expect(path).not.toBeNull();
  const bytes = await readFile(path ?? "");
  expect(bytes.subarray(0, 5).toString()).toBe("%PDF-");
  expect(
    (
      await context.request.get(`/api/projects/${project.id}/snapshots`)
    ).status(),
  ).toBe(200);
  expect(
    await (
      await context.request.get(`/api/projects/${project.id}/snapshots`)
    ).json(),
  ).toHaveLength(0);
  await editor.fill(
    "\\documentclass{article}\n\\begin{document}\n\\UnknownCommand\n\\end{document}",
  );
  await expect(page.locator(".pdf-file-label")).toContainText("Older output");
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compilation failed", { timeout: 30_000 });
  await expect(
    page.getByRole("button", { name: "Download PDF", exact: true }),
  ).toBeEnabled();
  await expect(page.locator(".compile-diagnostics")).toContainText(
    "Undefined control sequence",
  );
  await page.getByRole("button", { name: "main.tex:3", exact: true }).click();
  await expect(editor).toBeFocused();
  const loop =
    "\\documentclass{article}\\begin{document}\\def\\forever{\\forever}\\forever\\end{document}";
  await editor.fill(loop);
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compiling…", { timeout: 15_000 });
  await page.getByRole("button", { name: "Cancel compile" }).click();
  await expect(status).toHaveText("Compilation cancelled");
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compilation timed out", { timeout: 25_000 });
  await editor.fill(
    await readFile("tests/fixtures/compiler/resume-unicode/main.tex", "utf8"),
  );
  await page.getByLabel("Auto compile", { exact: true }).check();
  await expect(status).toHaveText("Compilation succeeded", { timeout: 30_000 });
  await page.getByLabel("Auto compile", { exact: true }).uncheck();
  await expect(page.locator(".pdf-message")).toHaveText("Page 1 ready.");
  await page.screenshot({
    path: testInfo.outputPath("compiled-workspace.png"),
    fullPage: true,
  });
  const currentDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  const result = await currentDownload;
  const pdf = await readFile((await result.path()) ?? "");
  const expectedHash = createHash("sha256").update(pdf).digest("hex");
  await page
    .getByRole("button", { name: "Analyze resume PDF", exact: true })
    .click();
  await expect(page).toHaveURL(/\/resume$/);
  await expect(page.locator(".hash-label")).toContainText(expectedHash, {
    timeout: 20_000,
  });
  await expect(
    page.getByText(/Generated locally from saved revision/),
  ).toBeVisible();
  await page
    .getByText("Inspect all extracted text and page locations", { exact: true })
    .click();
  await expect(page.locator(".extracted-text")).toContainText("Zoë García");
  await page.goto(`/projects/${project.id}`);
  await expect(editor).toBeVisible();
  await editor.fill(loop);
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compiling…", { timeout: 30_000 });
  const second = await context.request.post("/api/projects", {
    headers: { origin },
    data: { name: "Other project" },
  });
  const other = await second.json();
  await page.goto(`/projects/${other.id}`);
  await expect(
    page.getByRole("button", { name: "Download PDF", exact: true }),
  ).toHaveCount(0);
  await expect(status).toHaveText("Ready to compile");
});

test("real image compile, asset ZIP/history restore, nested main file and mobile preview", async ({
  page,
  context,
}, testInfo) => {
  test.setTimeout(120_000);
  test.skip(
    !process.env.TEST_DATABASE_URL ||
      !existsSync("apps/web/public/compiler/manifest.json"),
    "Requires real PostgreSQL and compiler:prepare assets",
  );
  const signin = await context.request.post("/api/auth/sign-in/email", {
    headers: { origin },
    data: { email, password: "synthetic-compiler-password-42" },
  });
  expect(signin.status()).toBe(200);
  const response = await context.request.post("/api/projects", {
    headers: { origin },
    data: { name: "Report and image" },
  });
  const project = await response.json();
  const url = `/api/projects/${project.id}`;
  await page.goto(`/projects/${project.id}`);
  const editor = page.getByRole("textbox", {
    name: "Source editor: main.tex",
    exact: true,
  });
  await expect(editor).toBeVisible();
  const status = page.getByRole("status", { name: "Compilation status" });
  await editor.fill(
    await readFile("tests/fixtures/compiler/report/chart.tex", "utf8"),
  );
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compilation succeeded", { timeout: 45_000 });
  const chartDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  const chart = await chartDownload;
  const image = await readFile((await chart.path()) ?? "");
  await page.getByText("Main file & images", { exact: true }).click();
  await page.getByLabel("Upload project image").setInputFiles({
    name: "chart.pdf",
    mimeType: "application/pdf",
    buffer: image,
  });
  await page.getByRole("button", { name: "Save image", exact: true }).click();
  await expect(editor).toBeVisible();
  await expect
    .poll(
      async () =>
        (await (await context.request.get(url)).json()).assets?.length,
    )
    .toBe(1);
  const method = await context.request.post(`${url}/files`, {
    headers: { origin },
    data: {
      baseRevision: (await (await context.request.get(url)).json()).revision,
      path: "sections/method.tex",
      content: await readFile(
        "tests/fixtures/compiler/report/sections/method.tex",
        "utf8",
      ),
    },
  });
  expect(method.status()).toBe(201);
  await page.reload();
  await expect(editor).toBeVisible();
  await editor.fill(
    await readFile("tests/fixtures/compiler/report/main.tex", "utf8"),
  );
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compilation succeeded", { timeout: 30_000 });
  await expect(
    page.getByRole("img", { name: "PDF page 1 of 4" }),
  ).toBeVisible();
  await page.getByRole("button", { name: "Next PDF page" }).click();
  await page.getByRole("button", { name: "Next PDF page" }).click();
  await expect(page.locator(".pdf-message")).toHaveText("Page 3 ready.");
  await page.screenshot({
    path: testInfo.outputPath("compiled-report-image.png"),
    fullPage: true,
  });
  await page.getByRole("button", { name: "History", exact: true }).click();
  const history = page.getByRole("dialog", { name: "Recoverable history" });
  await history
    .getByRole("textbox", { name: "Snapshot name" })
    .fill("With original image");
  await history.getByRole("button", { name: "Save named snapshot" }).click();
  await expect(history.getByText("Named snapshot saved.")).toBeVisible();
  await history.getByRole("button", { name: "Close history" }).click();
  const snapshots = await (
    await context.request.get(`${url}/snapshots`)
  ).json();
  const original = snapshots.find(
    (s: { name: string }) => s.name === "With original image",
  );
  expect(original).toBeTruthy();
  await page.getByText("Main file & images", { exact: true }).click();
  await page.getByLabel("Upload project image").setInputFiles({
    name: "chart.pdf",
    mimeType: "application/pdf",
    buffer: Buffer.concat([image, Buffer.from("\n% replacement")]),
  });
  await page.getByRole("button", { name: "Save image", exact: true }).click();
  await expect
    .poll(
      async () =>
        (await (await context.request.get(url)).json()).assets?.[0]?.version,
    )
    .toBe(2);
  await page.getByRole("button", { name: "History", exact: true }).click();
  await expect(history).toBeVisible();
  await history
    .getByRole("button", { name: `Compare r${original.revision}`, exact: true })
    .click();
  await expect(
    history.getByRole("list", { name: "Asset changes" }),
  ).toContainText("chart.pdf");
  await history
    .getByRole("button", {
      name: `Restore snapshot r${original.revision}`,
      exact: true,
    })
    .click();
  await expect(history).toHaveCount(0);
  await expect(editor).toBeVisible();
  const restored = await (await context.request.get(url)).json();
  expect(restored.assets[0].dataBase64).toBe(image.toString("base64"));
  expect(restored.assets[0].version).toBe(3);
  const zipEvent = page.waitForEvent("download");
  await page
    .getByRole("button", { name: "Export project (.zip)", exact: true })
    .click();
  const zip = await zipEvent;
  const archive = await readFile((await zip.path()) ?? "");
  expect(archive.includes(image)).toBe(true);
  expect(archive.includes(Buffer.from("source/chart.pdf"))).toBe(true);
  const alternate = await context.request.post(`${url}/files`, {
    headers: { origin },
    data: {
      baseRevision: (await (await context.request.get(url)).json()).revision,
      path: "nested/alternate.tex",
      content:
        "\\documentclass{article}\\begin{document}Nested main file\\end{document}",
    },
  });
  expect(alternate.status()).toBe(201);
  await page.reload();
  await expect(editor).toBeVisible();
  await page.getByText("Main file & images", { exact: true }).click();
  await page
    .getByLabel("Main LaTeX file", { exact: true })
    .selectOption("nested/alternate.tex");
  await expect(
    page.getByRole("textbox", {
      name: "Source editor: nested/alternate.tex",
      exact: true,
    }),
  ).toBeVisible();
  await page.getByRole("button", { name: "▷ Recompile" }).click();
  await expect(status).toHaveText("Compilation succeeded", { timeout: 30_000 });
  await expect(page.locator(".pdf-message")).toHaveText("Page 1 ready.");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "PDF preview", exact: true }).click();
  expect(
    await page.evaluate(
      () => document.documentElement.scrollWidth <= window.innerWidth,
    ),
  ).toBe(true);
  await page.screenshot({
    path: testInfo.outputPath("compiled-mobile.png"),
    fullPage: true,
  });
});
